package com.example.data.local

data class TacticalPuzzle(
    val id: String,
    val title: String,
    val fen: String,
    val solutionUci: List<String>,
    val rating: Int,
    val themes: List<String>,
    val hint: String,
    val explanation: String,
    val isCheckmatePattern: Boolean = false,
    val patternName: String = "",
)

data class LessonStep(
    val title: String,
    val explanation: String,
    val fen: String,
    val expectedMoveUci: String?, // null = reading/example step
    val hint: String = "",
)

data class ChessLesson(
    val id: String,
    val level: String, // Beginner, Intermediate, Advanced
    val category: String,
    val title: String,
    val summary: String,
    val steps: List<LessonStep>,
)

data class EndgameExercise(
    val id: String,
    val category: String,
    val title: String,
    val objective: String,
    val fen: String,
    val bestStartUci: String,
    val tip: String,
)

data class OpeningDrill(
    val id: String,
    val eco: String,
    val title: String,
    val isGambit: Boolean,
    val side: String, // "White" or "Black"
    val lineMovesUci: List<String>,
    val targetFen: String,
    val expectedMoveUci: String,
    val keyIdea: String,
)

